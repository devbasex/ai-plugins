"""cross-refactoring（M4 #3298）。

判断は名前が `_decide.py` で終わる純粋なモジュールが持ち、git・ファイル・外部のコマンドを読む部分は同名の殻が持つ。

| モジュール | 中身 |
| --- | --- |
| `diff_decide` | 差分（`git diff -U0`）から、ファイルごとに触った行を読む |
| `symbols_decide` | 触った行を含む関数・クラスを引き、提案を課題が触る関数へ絞る（#622） |
| `tests_decide` | テストのファイルの見分け・触ったモジュールに対応するテストの選び方（#3049）・着手前の範囲テストのファイル（#2096）・収集の判定（#620） |
| `probe_decide` | テンプレートの試走の上限（#2158） |
| `final_gate_decide` | 最終ゲートの直しの範囲外の検出（#3038）と、CI を待つ前の衝突の判定（#2680） |
| `launch_decide` | 担当の結果ファイルの置き場（#750） |
| `finished_decide` | 完了した回を返すときの案内（#2057） |
| `phase_decide` | 工程の起点の記録と、担当が結果を出さずに終わったときの続け方（#3313） |
| `scope` | 殻: 差分と作業場所のファイルを読み、触る関数と範囲テストのファイルを組む |
| `collect` | 殻: 宣言の `collect_command` を打ち、足したテストが全体の実行に収集されるかを確かめる |
| `items_decide` | 提案をまとめ、触る関数を指す提案だけを項目にする（#622） |
| `verify_decide` | 項目の起点から在った失敗を項目の失敗に数えない判定（#3339）と、修正の前進（停滞・振動） |
| `range_decide` | 検査のプランが `--scope` へ渡す範囲（#1484） |
| `budget_decide` | 実装の予算で採る項目を選ぶ判定と、安全網（コードを書く工程の起動の秒の累計の上限） |
| `judge_decide` | 修正が停滞か振動した項目の成立の判定と、その後の続け方 |
| `flaky_decide` | フレーキーな失敗の見分けと、直しのコミットの手順の違反の判定 |
| `report_decide` | リファクタリング計画のコメントと完了報告の本文 |
| `prompt_decide` | 工程の担当へ渡す指示文（提案・計画・テストの追加・実装・修正・成立の判定・フレーキーの直し・最終ゲートの直し） |
| `store` | 殻: 状態ファイル |
| `workspace` | 殻: 作業場所の準備と片付け（置き場・lock・再開の確かめは `ndf.core.converge`。#3106） |
| `launch` | 殻: 工程の担当の起動と結果の回収（#750） |
| `verify` | 殻: 宣言の検査とテストをファイルごとに当て、落ちた鍵を集める |
| `final_gate` | 殻: 最終ゲート（送る・衝突の確かめ・CI の待ち・対象範囲の中だけの直し） |
| `drive` | 1 回の実行の駆動（提案 → 計画と予算 → 項目ごとのテストの追加・実装・検証と修正・成立の判定・フレーキーの直し → 最終ゲート → 計画のコメントと完了報告） |
| `cli` | 副命令 `refactor` |

相手役の割り当て・作業場所の lock・同期・片付けは cross 系で共通の `ndf.core.converge` が持つ。兄弟の `domains` は読まない。
"""
